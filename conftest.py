import json
import os

import pytest
import requests
from fastapi.testclient import TestClient

from api_client import APIClient
from practice_api import app

DEFAULT_EXTERNAL_API_URL = "https://jsonplaceholder.typicode.com"


@pytest.fixture(scope="session")
def external_api_url() -> str:
    """Base URL of the external demo API; override with EXTERNAL_API_URL."""
    return os.getenv("EXTERNAL_API_URL", DEFAULT_EXTERNAL_API_URL).rstrip("/")


@pytest.fixture
def api_client(external_api_url):
    return APIClient(external_api_url)


@pytest.fixture
def local_api():
    """In-process client for the practice FastAPI app; no server required."""
    with TestClient(app) as client:
        yield client


@pytest.fixture(scope="session")
def openapi_spec() -> dict:
    """OpenAPI document generated by the in-process practice app."""
    return app.openapi()


@pytest.fixture(scope="session")
def backend_openapi_spec() -> dict:
    """Spec of a real backend service; skipped unless OPENAPI_SPEC_URL is set.

    Accepts an http(s) URL or a local file path (JSON).
    """
    source = os.getenv("OPENAPI_SPEC_URL")
    if not source:
        pytest.skip("OPENAPI_SPEC_URL not set")

    if source.startswith(("http://", "https://")):
        response = requests.get(source, timeout=15)
        response.raise_for_status()
        return response.json()

    with open(source, encoding="utf-8") as spec_file:
        return json.load(spec_file)


@pytest.fixture
def api_session():
    session = requests.Session()
    yield session
    session.close()
